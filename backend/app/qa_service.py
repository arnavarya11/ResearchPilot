
import json
import urllib.error
import urllib.request

from backend.app.semantic_search import search_semantic


OLLAMA_URL = "http://localhost:11434/api/chat"
OLLAMA_MODEL = "llama3.2:3b"


def answer_question(
    question: str,
    limit: int = 5,
    filename: str | None = None,
) -> dict:
    """Answer a research question using retrieved paper passages."""

    question = question.strip()

    if not question:
        raise ValueError("Question cannot be empty.")

    # Retrieve relevant passages from the uploaded research papers.
    results = search_semantic(
        question,
        limit=limit,
        filename=filename,
    )

    if not results:
        return {
            "question": question,
            "answer": (
                "I could not find relevant passages in the "
                "available research papers."
            ),
            "citations": [],
            "sources_found": 0,
        }

    # Give every retrieved passage a citation number.
    evidence_sections = []

    for index, result in enumerate(results, start=1):
        evidence_sections.append(
            f"[{index}]\n"
            f"Paper: {result['filename']}\n"
            f"Page: {result['page_number']}\n"
            f"Passage:\n{result['text']}"
        )

    evidence = "\n\n".join(evidence_sections)

    prompt = f"""
You are ResearchPilot, an assistant for understanding research papers.

Answer the user's question using ONLY the evidence passages below.

Rules:
1. Do not invent facts, results, statistics, or references.
2. Cite supporting passages using their bracketed numbers, such as [1].
3. If the passages do not contain enough information, clearly say so.
4. Distinguish information stated in the papers from your own explanation.
5. Be clear, accurate, and useful for academic research.
6. Never invent a paper title, page number, or citation.

EVIDENCE PASSAGES:
{evidence}

USER QUESTION:
{question}
"""

    payload = {
        "model": OLLAMA_MODEL,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are a careful research assistant. "
                    "Use only the supplied evidence and do not "
                    "fabricate citations."
                ),
            },
            {"role": "user", "content": prompt},
        ],
        "stream": False,
    }

    request = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(request, timeout=180) as response:
            model_response = json.loads(response.read().decode("utf-8"))

    except urllib.error.URLError as exc:
        raise RuntimeError(
            "Could not connect to Ollama. Make sure Ollama is running."
        ) from exc

    answer = model_response["message"]["content"]

    # Citation metadata comes from the database search results,
    # not from text generated by the model.
    citations = [
        {
            "citation_number": index,
            "filename": result["filename"],
            "page_number": result["page_number"],
            "chunk_id": result["chunk_id"],
            "similarity": result["similarity"],
            "excerpt": result["text"],
        }
        for index, result in enumerate(results, start=1)
    ]

    return {
        "question": question,
        "answer": answer,
        "citations": citations,
        "sources_found": len(citations),
    }
